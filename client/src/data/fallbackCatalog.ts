export function getFallbackProducts(filters: ProductFilters = {}): PaginatedResponse<Product> {
  let list = [...FALLBACK_PRODUCTS];

  if (filters.category) {
    list = list.filter((p) => p.category.slug === filters.category);
  }
  if (filters.search) {
    const q = filters.search.toLowerCase();
    list = list.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.tags.some((t) => t.toLowerCase().includes(q))
    );
  }
  if (filters.featured) {
    list = list.filter((p) => p.isFeatured);
  }
  if (filters.sale) {
    list = list.filter((p) => p.compareAtPrice && p.compareAtPrice > p.price);
  }
  if (filters.newArrivals) {
    list = list.filter((p) => p.isNewArrival);
  }
  if (filters.minPrice !== undefined) {
    list = list.filter((p) => p.price >= filters.minPrice!);
  }
  if (filters.maxPrice !== undefined) {
    list = list.filter((p) => p.price <= filters.maxPrice!);
  }

  if (filters.sort) {
    if (filters.sort === 'price:asc') list.sort((a, b) => a.price - b.price);
    else if (filters.sort === 'price:desc') list.sort((a, b) => b.price - a.price);
    else if (filters.sort === 'name:asc') list.sort((a, b) => a.name.localeCompare(b.name));
    else if (filters.sort === 'name:desc') list.sort((a, b) => b.name.localeCompare(a.name));
    else if (filters.sort === 'avgRating:desc') list.sort((a, b) => b.avgRating - a.avgRating);
  }

  const page = filters.page || 1;
  const limit = filters.limit || 12;
  const total = list.length;
  const start = (page - 1) * limit;
  const data = list.slice(start, start + limit);

  return {
    success: true,
    statusCode: 200,
    message: 'Products retrieved',
    data,
    pagination: {
      page,
      limit,
      total,
      totalPages: Math.ceil(total / limit),
      hasMore: start + limit < total,
    },
  };
}

export function getFallbackProduct(slug: string): Product | undefined {
  return FALLBACK_PRODUCTS.find((p) => p.slug === slug);
}
